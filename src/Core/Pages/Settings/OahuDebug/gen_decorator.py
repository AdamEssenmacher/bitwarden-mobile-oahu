#!/usr/bin/env python3
"""Writes a forwarding decorator for a C# interface: every member forwards to _inner, except the names given.

usage: gen_decorator.py <interface.cs> <ClassName> <namespace> <out.cs> [skip names...]
"""
import re
import sys

src, cls, ns, out, *skip = sys.argv[1:]
text = open(src, encoding="utf-8-sig").read()
iface = re.search(r"interface\s+(\w+)", text).group(1)
body = text[text.index("{", text.index("interface")) + 1:]
lines = [l.strip() for l in body.splitlines()]
members = []
for l in lines:
    if not l or l.startswith("//") or l.startswith("[") or l in ("{", "}"):
        continue
    if l.endswith("}") and "{ get;" in l:
        members.append(l)
        continue
    if not l.endswith(";"):
        raise SystemExit("multi-line member: " + l)
    members.append(l[:-1])


def split_params(p):
    parts, depth, cur = [], 0, ""
    for ch in p:
        if ch in "<([":
            depth += 1
        elif ch in ">)]":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        parts.append(cur)
    return [x.strip() for x in parts]


out_lines = [
    "// <auto-generated> by gen_decorator.py from " + src.split("/")[-1] + ". DEBUG only: see OahuDebugStateService.cs.",
    "#if DEBUG",
    "#pragma warning disable CS0618 // forwards obsolete members too",
    "using Bit.Core.Abstractions;",
    "using Bit.Core.Enums;",
    "using Bit.Core.Models.Data;",
    "using Bit.Core.Models.Domain;",
    "using Bit.Core.Models.Response;",
    "using Bit.Core.Models.View;",
    "using BwRegion = Bit.Core.Enums.Region;",
    "",
    "namespace " + ns,
    "{",
    "    public sealed partial class " + cls + " : " + iface,
    "    {",
]
for m in members:
    prop = re.match(r"(.+?)\s+(\w+)\s*\{\s*get;\s*(set;)?\s*\}$", m)
    if prop:
        t, name, setter = prop.groups()
        if name in skip:
            continue
        acc = "get => _inner." + name + ";" + (" set => _inner." + name + " = value;" if setter else "")
        out_lines.append(f"        public {t} {name} {{ {acc} }}")
        continue
    meth = re.match(r"(.+?)\s+(\w+)(<[^>]+>)?\((.*)\)$", m)
    if not meth:
        raise SystemExit("unparsed: " + m)
    ret, name, gen, params = meth.groups()
    if name in skip:
        continue
    names = []
    for p in split_params(params):
        p = p.split("=")[0].strip()
        names.append(p.split()[-1])
    out_lines.append(f"        public {ret} {name}{gen or ''}({params}) => _inner.{name}({', '.join(names)});")
out_lines += ["    }", "}", "#endif", ""]
open(out, "w").write("\n".join(out_lines))
print(len(members), "members")
